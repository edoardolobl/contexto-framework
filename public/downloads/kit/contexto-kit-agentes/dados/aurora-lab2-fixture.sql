-- Dialeto: SQLite 3. lab2_eventos_diarios espelha a tabela de produção aurora_prod.tracking.eventos_diarios:
-- não há linha nos dias em que o evento não disparou. A carga de 2026-11-16 ainda está incompleta (regra D+2).
PRAGMA foreign_keys = ON;

CREATE TABLE lab2_plano (
  event_name TEXT NOT NULL,
  operation TEXT NOT NULL,
  active INTEGER NOT NULL CHECK (active IN (0, 1)),
  launch_date TEXT NOT NULL,
  silence_tolerance_days INTEGER NOT NULL,
  PRIMARY KEY (event_name, operation)
);

CREATE TABLE lab2_eventos_diarios (
  event_date TEXT NOT NULL,
  operation TEXT NOT NULL,
  event_name TEXT NOT NULL,
  event_count INTEGER NOT NULL CHECK (event_count > 0),
  PRIMARY KEY (event_date, operation, event_name)
);

CREATE TABLE lab2_carga (
  event_date TEXT NOT NULL,
  operation TEXT NOT NULL,
  is_complete INTEGER NOT NULL CHECK (is_complete IN (0, 1)),
  PRIMARY KEY (event_date, operation)
);

CREATE TABLE lab2_pedidos (
  order_id TEXT PRIMARY KEY,
  order_date TEXT NOT NULL,
  operation TEXT NOT NULL,
  revenue INTEGER NOT NULL
);

CREATE TABLE lab2_itens (
  item_id TEXT PRIMARY KEY,
  order_id TEXT NOT NULL REFERENCES lab2_pedidos(order_id),
  sku TEXT NOT NULL
);

